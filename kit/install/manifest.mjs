// The project's ownership record `.agents/harness-kit.json` (INST-05, INST-31, INST-32).
import fs from "node:fs";
import path from "node:path";
import { readJson, writeJsonAtomic } from "../../ship/.agents/harness/lib/io.mjs";
import { byCodePoint } from "./units.mjs";
import { fail, KitFailure } from "./failure.mjs";

export const MANIFEST_REL = ".agents/harness-kit.json";
export const OLDER_MANIFEST = `${MANIFEST_REL} was written by an older kit; move it aside (e.g. to .agents/harness-kit.old.json) and run install`;
const NOTES = "Generated by paseo-kit install/update/pull: the kit-owned parts of this project and their digests (sha256 of the text with CRLF as LF). Do not edit; run the kit's status, update or pull verbs.";
const DIGEST = /^[0-9a-f]{64}$/;

export const manifestFile = (project) => path.join(project, MANIFEST_REL);

const isPlainObject = (v) => v !== null && typeof v === "object" && !Array.isArray(v);

export function isCurrentFormat(m) {
  return isPlainObject(m) && !Object.hasOwn(m, "kit") && typeof m.version === "string" && isPlainObject(m.files)
    && Object.values(m.files).every((d) => typeof d === "string" && DIGEST.test(d));
}

// null when absent; an older-format manifest is refused without being used (INST-31).
export function readManifest(project) {
  const file = manifestFile(project);
  if (!fs.existsSync(file)) return null;
  let m;
  try {
    m = readJson(file);
  } catch (e) {
    throw new KitFailure(`${MANIFEST_REL}: ${e.code === "EJSON" ? "invalid JSON" : e.message}`);
  }
  if (!isCurrentFormat(m)) fail(OLDER_MANIFEST);
  return m;
}

export function requireManifest(project) {
  return readManifest(project) ?? fail("not installed; use install");
}

export function writeManifest(project, { version, installedAt, files }, now = new Date()) {
  const sorted = Object.fromEntries(Object.keys(files).sort(byCodePoint).map((k) => [k, files[k]]));
  const updatedAt = now.toISOString();
  writeJsonAtomic(manifestFile(project), { _notes: NOTES, version, installedAt: installedAt ?? updatedAt, updatedAt, files: sorted });
}
